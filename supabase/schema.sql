-- Run this file once in Supabase Dashboard > SQL Editor.
-- It creates the portfolio content tables and restricts all CRUD operations to
-- authenticated users whose profile role is "admin".

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'editor' check (role in ('admin', 'editor')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id) values (new.id)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Also create a default profile for accounts that existed before this script ran.
insert into public.profiles (id)
select id from auth.users
on conflict (id) do nothing;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.certification (
  id bigint generated by default as identity primary key,
  title text not null,
  issuer text not null,
  issued_date date,
  credential_url text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.education (
  id bigint generated by default as identity primary key,
  title text not null,
  institution text not null,
  start_date date,
  end_date date,
  description text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.experience (
  id bigint generated by default as identity primary key,
  title text not null,
  company text not null,
  start_date date,
  end_date date,
  description text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.project (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null,
  thumbnail_url text,
  images jsonb not null default '[]'::jsonb,
  technologies jsonb not null default '[]'::jsonb,
  github_url text,
  demo_url text,
  is_featured boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tech_stack (
  id bigint generated by default as identity primary key,
  name text not null,
  icon_url text,
  category text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Keep updated_at accurate on each update.
drop trigger if exists set_certification_updated_at on public.certification;
create trigger set_certification_updated_at before update on public.certification for each row execute procedure public.set_updated_at();
drop trigger if exists set_education_updated_at on public.education;
create trigger set_education_updated_at before update on public.education for each row execute procedure public.set_updated_at();
drop trigger if exists set_experience_updated_at on public.experience;
create trigger set_experience_updated_at before update on public.experience for each row execute procedure public.set_updated_at();
drop trigger if exists set_project_updated_at on public.project;
create trigger set_project_updated_at before update on public.project for each row execute procedure public.set_updated_at();
drop trigger if exists set_tech_stack_updated_at on public.tech_stack;
create trigger set_tech_stack_updated_at before update on public.tech_stack for each row execute procedure public.set_updated_at();

alter table public.profiles enable row level security;
alter table public.certification enable row level security;
alter table public.education enable row level security;
alter table public.experience enable row level security;
alter table public.project enable row level security;
alter table public.tech_stack enable row level security;

-- Signed-in users can only inspect their own role. Role changes stay in SQL Editor.
drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile" on public.profiles for select to authenticated using (id = auth.uid());

-- Public visitors may read portfolio content. Only admins may create, update, or delete it.
drop policy if exists "Public can read certifications" on public.certification;
drop policy if exists "Admins manage certifications" on public.certification;
create policy "Public can read certifications" on public.certification for select using (true);
create policy "Admins manage certifications" on public.certification for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Public can read education" on public.education;
drop policy if exists "Admins manage education" on public.education;
create policy "Public can read education" on public.education for select using (true);
create policy "Admins manage education" on public.education for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Public can read experience" on public.experience;
drop policy if exists "Admins manage experience" on public.experience;
create policy "Public can read experience" on public.experience for select using (true);
create policy "Admins manage experience" on public.experience for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Public can read projects" on public.project;
drop policy if exists "Admins manage projects" on public.project;
create policy "Public can read projects" on public.project for select using (true);
create policy "Admins manage projects" on public.project for all to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Public can read tech stack" on public.tech_stack;
drop policy if exists "Admins manage tech stack" on public.tech_stack;
create policy "Public can read tech stack" on public.tech_stack for select using (true);
create policy "Admins manage tech stack" on public.tech_stack for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Required for authenticated admins to use identity columns.
grant select on public.certification, public.education, public.experience, public.project, public.tech_stack to anon, authenticated;
grant insert, update, delete on public.certification, public.education, public.experience, public.project, public.tech_stack to authenticated;
grant usage on all sequences in schema public to authenticated;

